'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const pluginRoot = path.resolve(__dirname, '..');
const repositoryRoot = path.resolve(pluginRoot, '..');
const codePath = path.join(pluginRoot, 'code.js');
const skillName = 'SKILL_UI_Mermaid_Writer_v1.3.md';
const specificationName = 'UI控件交互图_Mermaid转写规范_v2.3.md';
const startMarker = '/* DEEPSEEK_RULEBOOK_BUNDLE_START */';
const endMarker = '/* DEEPSEEK_RULEBOOK_BUNDLE_END */';

function readNormalized(filePath) {
  return fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}

function sha256(text) {
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

function main() {
  const skill = readNormalized(path.join(repositoryRoot, skillName));
  const specification = readNormalized(path.join(repositoryRoot, specificationName));
  const manifest = {
    skill: skillName,
    skillSha256: sha256(skill),
    specification: specificationName,
    specificationSha256: sha256(specification)
  };
  const bundle = [
    startMarker,
    '// Generated by plugin/scripts/embed-deepseek-rulebook.js. Do not edit this block by hand.',
    'var DEEPSEEK_RULEBOOK_MANIFEST = ' + JSON.stringify(manifest) + ';',
    'var DEEPSEEK_SKILL_DOCUMENT = ' + JSON.stringify(skill) + ';',
    'var DEEPSEEK_SPECIFICATION_DOCUMENT = ' + JSON.stringify(specification) + ';',
    endMarker
  ].join('\n');

  const source = readNormalized(codePath);
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start);
  if (start < 0 || end < 0) throw new Error('DeepSeek rulebook bundle markers are missing from plugin/code.js');
  const next = source.slice(0, start) + bundle + source.slice(end + endMarker.length);
  fs.writeFileSync(codePath, next, 'utf8');
  console.log('Embedded complete DeepSeek rulebook:', manifest);
}

main();
